const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true});
 const page=await browser.newPage();
 const s={device:{connected:false,axes:[],buttons:[],effects:[]},hardware:{connected:true,values:{rotation:1080},port:'/dev/test'},relay:{running:false,log:[]},profiles:[{id:'a',name:'Saved A',game_id:null,settings:{rotation:900}}],active_profile:null,games:[],diagnostics:{items:[]}};
 const schema={groups:[{id:'base',label:'Wheelbase'}],settings:[{id:'rotation',label:'Steering rotation',group:'base',type:'number',min:90,max:2700,step:2,unit:'°'}]};
 const writes=[];
 await page.route('**/api/**',async route=>{
  const request=route.request(),path=new URL(request.url()).pathname;
  let data;
  if(path==='/api/state')data=s;
  else if(path==='/api/session')data={token:'mock'};
  else if(path==='/api/schema')data=schema;
  else if(path==='/api/profiles' && request.method()==='POST'){
    data=request.postDataJSON();writes.push(data);s.profiles=[data];
  }else if(path==='/api/hardware/connect')data={connected:true,values:{},error:'No supported settings replied',port:'/dev/test'};
  else throw Error('Unexpected mocked API request: '+request.method()+' '+path);
  await route.fulfill({json:structuredClone(data)});
 });
 await page.goto('http://127.0.0.1:8765/#profiles');
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.locator('[data-route=wheelbase]').click();
 await page.locator('#setting-rotation').fill('1080');
 await page.locator('[data-route=profiles]').click();
 await page.getByRole('button',{name:'Update profile',exact:true}).click();
 await page.waitForFunction(()=>!busy);
 assert.equal(writes[0].settings.rotation,1080,'Explicit device-matching edit must replace saved900');
 await page.locator('[data-route=wheelbase]').click();
 await page.locator('#setting-rotation').fill('1100');
 assert.equal(await page.locator('#apply-draft').isDisabled(),false);
 await page.locator('#setting-rotation').fill('-1');
 assert.equal(await page.locator('#apply-draft').isDisabled(),true,'Invalid numeric input blocks Apply');
 assert.equal(await page.locator('#setting-rotation').getAttribute('aria-invalid'),'true');
 await page.locator('[data-route=profiles]').click();
 assert.equal(await page.getByRole('button',{name:'Save profile',exact:true}).isDisabled(),true,'Invalid setting blocks Save');
 await page.locator('[data-route=wheelbase]').click();
 assert.equal(await page.locator('#setting-rotation').inputValue(),'-1','Invalid edit remains visible across routes');
 assert.match(await page.locator('#confirmed-rotation').innerText(),/Enter a value/);
 await page.locator('#setting-rotation').fill('1102');
 assert.equal(await page.locator('#apply-draft').isDisabled(),false,'Corrected value enables Apply');
 await page.getByRole('button',{name:'Read device settings',exact:true}).click();
 await page.waitForFunction(()=>!busy);
 assert.match(await page.locator('#toast').innerText(),/No supported settings replied/,'Connect partial/error must not show success');
 assert.equal(writes.length,1);
 await page.locator('[data-route=overview]').click();
 assert.equal(await page.locator('#relay-profile option[value=native]').innerText(),'Full input mapping','Full mapping option must not imply a direct device path');
 assert.match(await page.locator('#content').innerText(),/Both options create a virtual input device/);
 assert.match(await page.locator('#content').innerText(),/Keep the relay stopped for direct Assetto Corsa and ACC use/);
 s.relay={running:true,profile:'compact',pid:1234,log:[]};
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#relay-profile')?.value==='compact');
 assert.equal(await page.locator('#relay-profile').isDisabled(),true,'Running relay selection remains locked');
 assert.equal(await page.locator('#relay-profile').inputValue(),'compact','Reload must reflect compact running profile instead of default native');
 s.relay={running:true,profile:'native',pid:1234,log:[]};
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#relay-profile')?.value==='native');
 assert.equal(await page.locator('#relay-profile').isDisabled(),true);

 await browser.close();console.log('PASS: profile override, invalid draft blocks Apply/Save, invalid edit route persistence, correction recovery, connect error feedback, virtual relay wording, running relay selection after reload. All API requests intercepted; no hardware or relay actions.');
})().catch(error=>{console.error(error);process.exit(1)});
